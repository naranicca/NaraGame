# Emit a UV sphere obj. Hand-tuned segment counts so the resulting mesh
# is detailed enough to read as smooth without bloating the test asset.
# Run once and check in -- this isn't a build step.

$out = Join-Path $PSScriptRoot 'sphere.obj'
$rings = 16     # latitudes between the two poles
$segs  = 24     # longitudes around the equator
$radius = 1.0

$lines = New-Object System.Collections.Generic.List[string]
[void]$lines.Add('# UV sphere generated by gen-sphere.ps1')
[void]$lines.Add("# rings=$rings, segs=$segs, radius=$radius")
[void]$lines.Add('')

# Positions + normals (same direction since sphere is centered at origin
# with unit radius) + UVs (longitude -> u, latitude -> v).
# rings+1 latitude lines including the two poles; segs+1 longitudes so
# the seam vertex has its own UV column instead of wrapping.
for ($i = 0; $i -le $rings; $i++) {
    $phi = [Math]::PI * $i / $rings        # 0 (north pole) .. pi (south)
    $y = [Math]::Cos($phi)
    $r = [Math]::Sin($phi)
    for ($j = 0; $j -le $segs; $j++) {
        $theta = 2.0 * [Math]::PI * $j / $segs
        $x = $r * [Math]::Cos($theta)
        $z = $r * [Math]::Sin($theta)
        [void]$lines.Add("v $($x.ToString('0.######')) $($y.ToString('0.######')) $($z.ToString('0.######'))")
    }
}
[void]$lines.Add('')
for ($i = 0; $i -le $rings; $i++) {
    $phi = [Math]::PI * $i / $rings
    $y = [Math]::Cos($phi)
    $r = [Math]::Sin($phi)
    for ($j = 0; $j -le $segs; $j++) {
        $theta = 2.0 * [Math]::PI * $j / $segs
        $x = $r * [Math]::Cos($theta)
        $z = $r * [Math]::Sin($theta)
        [void]$lines.Add("vn $($x.ToString('0.######')) $($y.ToString('0.######')) $($z.ToString('0.######'))")
    }
}
[void]$lines.Add('')
for ($i = 0; $i -le $rings; $i++) {
    $v = 1.0 - ($i / $rings)
    for ($j = 0; $j -le $segs; $j++) {
        $u = $j / $segs
        [void]$lines.Add("vt $($u.ToString('0.######')) $($v.ToString('0.######'))")
    }
}
[void]$lines.Add('')

# Faces. Index = ring * (segs+1) + seg + 1 (.obj 1-based). One quad per
# (ring, seg) cell -- the loader fan-triangulates so we keep the source
# compact. North + south pole rings degenerate to triangles naturally
# since two of the four corners coincide.
$cols = $segs + 1
for ($i = 0; $i -lt $rings; $i++) {
    for ($j = 0; $j -lt $segs; $j++) {
        $a = $i * $cols + $j + 1
        $b = $a + 1
        $c = $a + $cols + 1
        $d = $a + $cols
        # Quad a-b-c-d (CCW from outside) with matching v/vt/vn indices.
        [void]$lines.Add("f $a/$a/$a $b/$b/$b $c/$c/$c $d/$d/$d")
    }
}

$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllLines($out, $lines, $utf8NoBom)
"wrote $out ($($lines.Count) lines)"
